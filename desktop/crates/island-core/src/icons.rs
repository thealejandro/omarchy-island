#[cfg(test)]
mod tests {
    use super::*;
    use crate::svg::{Cmd, parse};

    #[test]
    fn every_icon_reads_and_fits_its_box() {
        for icon in Icon::ALL {
            let cmds = parse(icon.path()).unwrap_or_else(|| panic!("{icon:?}"));
            assert!(matches!(cmds[0], Cmd::Move(_)), "{icon:?}");
            for c in cmds {
                let p = match c {
                    Cmd::Move(p) | Cmd::Line(p) | Cmd::Cubic(_, _, p) => p,
                    Cmd::Arc { to, .. } => to,
                    Cmd::Close => continue,
                };
                assert!(
                    (0.0..=VIEW).contains(&p.x) && (0.0..=VIEW).contains(&p.y),
                    "{icon:?}"
                );
            }
        }
    }
}
